import { test, expect } from '@playwright/test';
const backend = 'http://127.0.0.1:3111';
const frontend = process.env.JAM_UI_ORIGIN || 'http://127.0.0.1:3110';
test.afterEach(async ({ context }) => { await context.unrouteAll({ behavior: 'wait' }); });

for (const [width, theme] of [[390, 'dark'], [320, 'light']] as const) {
  test(`shared admin isolates exam modes ${width}px ${theme}`, async ({ page, context, request }, info) => {
    test.skip(process.env.JAM_MODE_FIXTURE !== '1', 'Requires the disposable JAM admin fixture');
    test.setTimeout(180000);
    const login = await request.post(`${backend}/auth/login`, { data: { email: 'browser-admin@example.test', password: 'Browser-fixture-123!' } });
    expect(login.ok()).toBeTruthy();
    const { token } = await login.json();
    await context.addCookies([{ name: 'access_session', value: 'local-admin-fixture', url: frontend }]);
    await context.route('**/backend-api/**', async route => {
      const url = new URL(route.request().url());
      const path = url.pathname.replace(/^\/backend-api/, '');
      if (path === '/auth/refresh') return route.fulfill({ json: { token } });
      const response = await route.fetch({ url: `${backend}${path}${url.search}` });
      await route.fulfill({ response });
    });
    await page.addInitScript(theme => { localStorage.setItem('ui-theme', theme); }, theme);
    await page.setViewportSize({ width, height: 900 });
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/admin');
    await expect(page.getByRole('heading', { name: 'SSC Question Bank', exact: true })).toBeVisible();
    await expect(page.getByText('50 of 250 questions', { exact: true })).toBeVisible();
    await expect(page.getByLabel('Filter by subject').locator('option')).toHaveCount(5);
    await page.getByRole('checkbox', { name: 'Select question fixture-0', exact: true }).check();
    await page.getByRole('button', { name: '+ Add Question', exact: true }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    // Close the editor through a cross-tab storage change while it is open.
    await page.evaluate(() => { localStorage.setItem('study-guru:exam-mode', 'iit-jam'); window.dispatchEvent(new StorageEvent('storage', { key: 'study-guru:exam-mode' })); });
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('heading', { name: 'IIT JAM Question Bank', exact: true })).toBeVisible();
    await expect(page.getByText('20 of 20 questions', { exact: true })).toBeVisible();
    await expect(page.locator('input[type="checkbox"]:checked')).toHaveCount(0);
    await expect(page.getByLabel('Filter by subject').locator('option')).toHaveCount(2);
    await expect(page.getByLabel('Filter by topic').locator('option')).toHaveCount(8);
    expect(await page.locator('tbody').innerText()).not.toContain('Solve the equation');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('jam-admin.png'), fullPage: true });
    await page.screenshot({ path: info.outputPath('jam-admin-header.png') });
    await page.getByRole('button', { name: '+ Add Question', exact: true }).click();
    await expect(page.getByLabel('Subject', { exact: true }).locator('option')).toHaveCount(2);
    await expect(page.getByLabel('Topic', { exact: true }).locator('option')).toHaveCount(8);
    await page.getByLabel('Topic', { exact: true }).selectOption('iit-jam-mechanics');
    await page.getByLabel('Question', { exact: true }).fill('Mode-scoped Physics question');
    for (const [index, letter] of ['a', 'b', 'c', 'd'].entries()) await page.getByLabel(`Option ${letter}`, { exact: true }).fill(String(index + 1));
    await page.getByLabel('Correct answer', { exact: true }).fill('2');
    const createdResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/api/questions'));
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    const created = await createdResponse;
    expect(created.status()).toBe(201);
    const { question } = await created.json();
    expect(question).toMatchObject({ subject: 'iit-jam-physics', topic: 'iit-jam-mechanics', quizTopic: 'iit-jam-mechanics' });
    await expect(page.getByRole('dialog')).toHaveCount(0);
    const wrongBank = await request.get(`${backend}/api/questions?examMode=ssc&search=${encodeURIComponent(question.id)}`);
    expect((await wrongBank.json()).questions).toEqual([]);
    const remove = await request.delete(`${backend}/api/questions/${question.questionUid}?examMode=iit-jam`, { headers: { Authorization: `Bearer ${token}` } });
    expect(remove.ok()).toBeTruthy();
    await page.goto('/admin/upload/question');
    await expect(page.getByRole('combobox', { name: 'Quiz Subject', exact: true })).toHaveValue('iit-jam-physics');
    await expect(page.getByRole('combobox', { name: 'Quiz Topic', exact: true }).locator('option')).toHaveCount(8);
    await expect(page.getByText('Study Mode Schema Blueprint')).toHaveCount(0);
    await page.goto('/admin/upload/bulk');
    const target = page.locator('select').filter({ has: page.locator('option[value="iit-jam-physics"]') }).first();
    await expect(target).toHaveValue('iit-jam-physics');
    await page.goto('/admin/upload/mock-tests');
    const exams = page.getByRole('combobox', { name: 'Target Exam', exact: true });
    await expect(exams).toHaveValue('iit-jam-physics');
    expect((await exams.locator('option').evaluateAll(options => options.map(option => (option as HTMLOptionElement).value))).every(value => value.startsWith('iit-jam'))).toBe(true);
    await page.getByRole('button', { name: /Fetch Live/ }).click();
    await expect(page.locator('td[data-label="Slot ID"]').filter({ hasText: /^jam-browser-test$/ })).toBeVisible();
    await expect(page.locator('td[data-label="Slot ID"]').filter({ hasText: /^browser-test$/ })).toHaveCount(0);
    await page.screenshot({ path: info.outputPath('jam-mock-admin.png'), fullPage: true });
    await page.getByRole('switch', { name: 'IIT JAM Mode' }).click();
    await expect(exams).toHaveValue('ssc-cgl');
    expect((await exams.locator('option').evaluateAll(options => options.map(option => (option as HTMLOptionElement).value))).some(value => value.startsWith('iit-jam'))).toBe(false);
    await expect(page.locator('td[data-label="Slot ID"]').filter({ hasText: /^jam-browser-test$/ })).toHaveCount(0);
    await page.getByRole('button', { name: /Fetch Live/ }).click();
    await expect(page.locator('td[data-label="Slot ID"]').filter({ hasText: /^browser-test$/ })).toBeVisible();
    await expect(page.locator('td[data-label="Slot ID"]').filter({ hasText: /^jam-browser-test$/ })).toHaveCount(0);
    await page.goto('/admin');
    await expect(page.getByText('50 of 250 questions', { exact: true })).toBeVisible();
    await expect(page.getByLabel('Filter by subject')).toHaveValue('');
    expect(await page.locator('tbody').innerText()).not.toContain('JAM fixture');
    await page.screenshot({ path: info.outputPath('ssc-admin.png'), fullPage: true });
    expect(errors).toEqual([]);
  });
}
