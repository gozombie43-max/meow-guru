export function getJamChapterGroup(section: string): RankedTopicGroup | undefined {
  if (!Object.hasOwn(chapterTitles, section)) return undefined;
  const titles = chapterTitles[section];
  const metadata = JAM_SECTIONS.find(item => item.slug === section);
  if (!titles || !metadata) return undefined;
  return {
    slug: section,
    label: metadata.title,
    eyebrow: 'IIT JAM Physics',
    description: 'Choose a chapter to begin your practice.',
    metricLabel: 'Priority',
    filters: [],
    topics: titles.map((title, index) => ({
      rank: index + 1,
      title,
      slug: title.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
      priority: 'Core',
    })),
  };
}
